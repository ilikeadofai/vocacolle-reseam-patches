#!/usr/bin/env python3
"""Generates AppStrings.kt: VocaColleStrings in the language of the Translate UI patch.

Reseam's string tables follow the phone's language, but text drawn inside VocaColle should match
the language VocaColle was patched into. Run after adding strings:
    python3 tools/gen_app_strings.py
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
xml = (root / "apps/vocacolle/settings/src/main/strings/values/strings.xml").read_text(encoding="utf-8")
names = re.findall(r'<string name="([a-z0-9_]+)"', xml)
camel = lambda n: re.sub(r"_([a-z0-9])", lambda m: m.group(1).upper(), n)
lines = [
    "// Generated by tools/gen_app_strings.py from the settings strings. Do not edit.",
    "package io.github.ilikeadofai.vocacolle.core",
    "",
    "import io.github.ilikeadofai.vocacolle.settings.VocaColleStrings",
    "",
    "/** [VocaColleStrings] in the Translate UI patch's language, for text drawn inside VocaColle. */",
    "object AppStrings {",
]
for n in names:
    lines.append(f'    val {camel(n)}: String get() = appText("{n}") {{ VocaColleStrings.{camel(n)} }}')
lines.append("}")
out = root / "apps/vocacolle/extensions/core/src/main/kotlin/io/github/ilikeadofai/vocacolle/core/AppStrings.kt"
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(names)} strings -> {out.relative_to(root)}")
